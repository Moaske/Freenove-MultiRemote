#!/usr/bin/env python3
"""Turn Material Design Icons into small alpha bitmaps for the remote.

The ESP32 can't draw SVG, so each icon becomes a grey-level mask that the
firmware tints with the theme's colours.

  python3 tools/make_icons.py <path to @mdi/svg's svg folder>

Writes:
  sd-card/remote/icons/<name>.a8   28x28, for the Home page buttons
  src/icons_mdi.h                  the few icons the firmware itself uses
  docs/icons.png                   an overview with the names, for ha.cfg

.a8 format: 'A' '8' width height, then width*height bytes of alpha (0..255).
Needs: pip install cairosvg pillow. Icons: Pictogrammers, Apache 2.0.
"""
import io
import os
import sys

import cairosvg
from PIL import Image, ImageDraw, ImageFont

# Icons you can give a Home page button (by these names, in ha.cfg).
LIBRARY = [
    "lightbulb", "lightbulb-outline", "lightbulb-group", "ceiling-light",
    "ceiling-light-multiple", "dome-light", "globe-light", "floor-lamp", "desk-lamp", "lamp",
    "lamps", "string-lights", "led-strip-variant", "wall-sconce", "chandelier",
    "track-light", "spotlight-beam", "outdoor-lamp", "pine-tree",
    "light-switch", "power-socket-eu", "power-plug", "power", "television",
    "speaker", "window-shutter", "roller-shade",
]

# Built into the firmware: (icon, size in px, C name).
BUILTIN = [
    ("home-assistant", 22, "HA_LOGO"),
    ("wifi", 16, "WIFI"),
    ("wifi-off", 16, "WIFI_OFF"),
    ("window-shutter", 14, "SHUTTER"),
    ("arrow-up-bold", 24, "ARROW_UP"),
    ("arrow-down-bold", 24, "ARROW_DOWN"),
    ("stop", 24, "STOP"),
    ("lightbulb", 28, "FALLBACK"),   # when a button's icon is missing
]


def alpha(svg_dir, name, size):
    with open(os.path.join(svg_dir, name + ".svg"), "rb") as f:
        png = cairosvg.svg2png(bytestring=f.read(), output_width=size, output_height=size)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    return img.getchannel("A").tobytes()


def sheet(svg_dir, path):
    """All LIBRARY icons in a grid with their names, in the remote's colours."""
    cols, cw, ch, pad, top = 6, 150, 118, 12, 56
    rows = (len(LIBRARY) + cols - 1) // cols
    W, H = pad + cols * (cw + pad), top + rows * (ch + pad) + pad
    img = Image.new("RGB", (W, H), (0x0E, 0x11, 0x16))
    d = ImageDraw.Draw(img)
    fdir = "/usr/share/fonts/truetype/dejavu/"
    try:
        big = ImageFont.truetype(fdir + "DejaVuSans-Bold.ttf", 20)
        small = ImageFont.truetype(fdir + "DejaVuSansCondensed.ttf", 14)
    except OSError:
        big = small = ImageFont.load_default()
    d.text((pad, 16), "Home page icons  -  use the name in ha.cfg:  switch = entity, label, NAME",
           font=big, fill=(0xE8, 0xEC, 0xF2))
    for i, name in enumerate(sorted(LIBRARY)):
        x = pad + (i % cols) * (cw + pad)
        y = top + (i // cols) * (ch + pad)
        d.rounded_rectangle((x, y, x + cw, y + ch), 10, fill=(0x16, 0x1B, 0x23), outline=(0x2A, 0x32, 0x40))
        mask = Image.frombytes("L", (56, 56), alpha(svg_dir, name, 56))
        tint = Image.new("RGB", (56, 56), (0xFB, 0xBF, 0x24))
        img.paste(tint, (x + (cw - 56) // 2, y + 14), mask)
        tw = d.textlength(name, font=small)
        d.text((x + (cw - tw) / 2, y + ch - 28), name, font=small, fill=(0xE8, 0xEC, 0xF2))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path, optimize=True)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    svg_dir = sys.argv[1]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

    out = os.path.join(root, "sd-card", "remote", "icons")
    os.makedirs(out, exist_ok=True)
    for name in LIBRARY:
        with open(os.path.join(out, name + ".a8"), "wb") as f:
            f.write(b"A8" + bytes([28, 28]) + alpha(svg_dir, name, 28))

    lines = [
        "// Generated by tools/make_icons.py from Material Design Icons",
        "// (Pictogrammers, Apache 2.0). Alpha masks, row by row.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "struct AlphaIcon { uint8_t w, h; const uint8_t* a; };",
        "",
    ]
    for name, size, cname in BUILTIN:
        data = alpha(svg_dir, name, size)
        lines.append(f"// {name}")
        lines.append(f"static const uint8_t ICON_{cname}_A[{len(data)}] PROGMEM = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const AlphaIcon ICON_{cname} = {{ {size}, {size}, ICON_{cname}_A }};")
        lines.append("")
    with open(os.path.join(root, "src", "icons_mdi.h"), "w") as f:
        f.write("\n".join(lines))
    sheet(svg_dir, os.path.join(root, "docs", "icons.png"))
    print(f"{len(LIBRARY)} icons in sd-card/remote/icons, {len(BUILTIN)} in src/icons_mdi.h, docs/icons.png")


if __name__ == "__main__":
    main()
