#!/usr/bin/env python3
"""Turn Material Design Icons into small alpha bitmaps for the remote.

The ESP32 can't draw SVG, so each icon becomes a grey-level mask that the
firmware tints with the theme's colours.

  python3 tools/make_icons.py <path to @mdi/svg's svg folder>

Writes:
  sd-card/remote/icons/<name>.a8   28x28, for the Home page buttons
  src/icons_mdi.h                  the few icons the firmware itself uses

.a8 format: 'A' '8' width height, then width*height bytes of alpha (0..255).
Needs: pip install cairosvg pillow. Icons: Pictogrammers, Apache 2.0.
"""
import io
import os
import sys

import cairosvg
from PIL import Image

# Icons you can give a Home page button (by these names, in ha.cfg).
LIBRARY = [
    "lightbulb", "lightbulb-outline", "lightbulb-group", "ceiling-light",
    "ceiling-light-multiple", "floor-lamp", "desk-lamp", "lamp", "lamps",
    "string-lights", "led-strip-variant", "wall-sconce", "chandelier",
    "track-light", "spotlight-beam", "outdoor-lamp", "pine-tree",
    "light-switch", "power-socket-eu", "power-plug", "power", "television",
    "monitor", "speaker", "fan", "coffee-maker", "kettle", "radiator",
    "fishbowl", "sofa", "bed-king", "desk", "window-shutter",
]

# Built into the firmware: (icon, size in px, C name).
BUILTIN = [
    ("home-assistant", 22, "HA_LOGO"),
    ("wifi", 16, "WIFI"),
    ("wifi-off", 16, "WIFI_OFF"),
    ("window-shutter", 14, "SHUTTER"),
    ("arrow-up-bold", 24, "ARROW_UP"),
    ("arrow-down-bold", 24, "ARROW_DOWN"),
    ("stop", 24, "STOP"),
    ("lightbulb", 28, "FALLBACK"),   # when a button's icon is missing
]


def alpha(svg_dir, name, size):
    with open(os.path.join(svg_dir, name + ".svg"), "rb") as f:
        png = cairosvg.svg2png(bytestring=f.read(), output_width=size, output_height=size)
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    return img.getchannel("A").tobytes()


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    svg_dir = sys.argv[1]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

    out = os.path.join(root, "sd-card", "remote", "icons")
    os.makedirs(out, exist_ok=True)
    for name in LIBRARY:
        with open(os.path.join(out, name + ".a8"), "wb") as f:
            f.write(b"A8" + bytes([28, 28]) + alpha(svg_dir, name, 28))

    lines = [
        "// Generated by tools/make_icons.py from Material Design Icons",
        "// (Pictogrammers, Apache 2.0). Alpha masks, row by row.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "struct AlphaIcon { uint8_t w, h; const uint8_t* a; };",
        "",
    ]
    for name, size, cname in BUILTIN:
        data = alpha(svg_dir, name, size)
        lines.append(f"// {name}")
        lines.append(f"static const uint8_t ICON_{cname}_A[{len(data)}] PROGMEM = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"static const AlphaIcon ICON_{cname} = {{ {size}, {size}, ICON_{cname}_A }};")
        lines.append("")
    with open(os.path.join(root, "src", "icons_mdi.h"), "w") as f:
        f.write("\n".join(lines))
    print(f"{len(LIBRARY)} icons in sd-card/remote/icons, {len(BUILTIN)} in src/icons_mdi.h")


if __name__ == "__main__":
    main()
